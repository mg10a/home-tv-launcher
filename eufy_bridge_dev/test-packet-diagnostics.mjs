import assert from 'node:assert/strict';
import {observeVideoPacket} from './packet-diagnostics.mjs';
process.env.EUFY_DIAGNOSTICS='true';
const owner={}; const output=[];
for(let i=0;i<20;i++) observeVideoPacket(owner,{signCode:0,data:Buffer.alloc(29)},{videoDataLength:7,videoSeqNo:i,streamType:2},Buffer.from([0,0,0,1,2,1,128]),22,false,i===0,s=>output.push(JSON.parse(s)));
assert.equal(output.length,2);
assert.equal(output[1].counts.packets,20);
assert.equal(output[1].counts.picture_start,20);
assert.equal(output[1].counts.length_mismatch,0);
assert.equal(output[1].counts.sequence_gaps,0);
assert(Object.values(output[1].counts).every(v=>typeof v==='number'));
const broken={}; let last;
for(let i=0;i<20;i++) observeVideoPacket(broken,{signCode:1,data:Buffer.alloc(23)},{videoDataLength:7,videoSeqNo:i*2,streamType:1},Buffer.from([0,0,0,1,2,0,0]),22,false,i===0,s=>last=JSON.parse(s));
assert.equal(last.counts.length_mismatch,20);
assert.equal(last.counts.short_encrypted,20);
assert.equal(last.counts.sequence_gaps,19);
assert.equal(last.counts.valid_hevc,0);
assert.equal(last.counts.codec_h264,20);
process.env.EUFY_DIAGNOSTICS='false';
observeVideoPacket({},null,null,null,0,false,true,()=>{throw Error('disabled diagnostic emitted')});
console.log('Packet counters, disabled mode and numeric-only output passed');
